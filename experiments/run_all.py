"""Run all four experiments in order, then write results/summary.md.

Usage (from the repo root):
    python experiments/run_all.py
"""

from __future__ import annotations

import os
import sys
import time
from datetime import date

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import common  # noqa: E402
import exp1_items  # noqa: E402
import exp2_capacity  # noqa: E402
import exp3_quality  # noqa: E402
import exp4_failure_cases  # noqa: E402

SUMMARY_PATH = common.results_path("summary.md")


def _mib(b: str) -> str:
    return f"{int(b) / (1024 * 1024):.2f} MiB"


def _ms(s: str) -> str:
    return f"{float(s) * 1000:.2f} ms"


def write_summary(timings: dict) -> None:
    e1 = common.read_csv(exp1_items.CSV_PATH)
    e2 = common.read_csv(exp2_capacity.CSV_PATH)
    e3 = common.read_csv(exp3_quality.SUMMARY_PATH)
    e4 = common.read_csv(exp4_failure_cases.CSV_PATH)

    def pick(rows, **kw):
        for r in rows:
            if all(str(r[k]) == str(v) for k, v in kw.items()):
                return r
        raise KeyError(kw)

    n_max = max(int(r["n"]) for r in e1)
    w_max = max(int(r["capacity"]) for r in e2)
    e1_dp = pick(e1, n=n_max, algorithm="dp_2d")
    e1_dp1 = pick(e1, n=n_max, algorithm="dp_1d")
    e1_gr = pick(e1, n=n_max, algorithm="greedy_ratio")
    e1_gv = pick(e1, n=n_max, algorithm="greedy_value")
    e2_dp = pick(e2, capacity=w_max, algorithm="dp_2d")
    e2_dp1 = pick(e2, capacity=w_max, algorithm="dp_1d")
    e2_gr = pick(e2, capacity=w_max, algorithm="greedy_ratio")

    ratio_all = pick(e3, greedy="greedy_ratio", correlation="all")
    value_all = pick(e3, greedy="greedy_value", correlation="all")

    speedup_n = float(e1_dp["seconds"]) / max(float(e1_gr["seconds"]), 1e-9)
    speedup_w = float(e2_dp["seconds"]) / max(float(e2_gr["seconds"]), 1e-9)

    lines = []
    lines.append("# Results summary")
    lines.append("")
    lines.append(f"Generated by `experiments/run_all.py` on {date.today().isoformat()}. "
                 "All numbers below are read from the CSV files in this folder.")
    lines.append("")
    lines.append("## Run times of the experiment scripts")
    lines.append("")
    for k, v in timings.items():
        lines.append(f"- {k}: {v:.1f} s")
    lines.append(f"- total: {sum(timings.values()):.1f} s")
    lines.append("")

    lines.append("## Experiment 1: items grow, capacity fixed (`exp1_items.csv`)")
    lines.append("")
    lines.append(f"At the largest size, n = {n_max}, W = {e1_dp['capacity']}:")
    lines.append("")
    lines.append("| algorithm | median runtime | peak memory | value | % of optimum |")
    lines.append("|---|---|---|---|---|")
    for r in (e1_dp, e1_dp1, e1_gr, e1_gv):
        lines.append(f"| {common.LABELS[r['algorithm']]} | {_ms(r['seconds'])} | {_mib(r['peak_bytes'])} | {r['value']} | {float(r['quality_percent']):.2f} |")
    lines.append("")
    lines.append(f"DP (2D) is about {speedup_n:.0f}x slower than greedy-by-ratio at n = {n_max}.")
    lines.append("Charts: `charts/exp1_runtime_vs_n.png`, `charts/exp1_memory_vs_n.png`.")
    lines.append("")

    lines.append("## Experiment 2: capacity grows, items fixed (`exp2_capacity.csv`)")
    lines.append("")
    lines.append(f"At the largest capacity, W = {w_max}, n = {e2_dp['n']}:")
    lines.append("")
    lines.append("| algorithm | median runtime | peak memory |")
    lines.append("|---|---|---|")
    for r in (e2_dp, e2_dp1, e2_gr):
        lines.append(f"| {common.LABELS[r['algorithm']]} | {_ms(r['seconds'])} | {_mib(r['peak_bytes'])} |")
    lines.append("")
    w_min = min(int(r["capacity"]) for r in e2)
    e2_dp_min = pick(e2, capacity=w_min, algorithm="dp_2d")
    lines.append(f"DP (2D) runtime went from {_ms(e2_dp_min['seconds'])} at W = {w_min} to "
                 f"{_ms(e2_dp['seconds'])} at W = {w_max} ({w_max // w_min}x more capacity), "
                 f"and its peak memory from {_mib(e2_dp_min['peak_bytes'])} to {_mib(e2_dp['peak_bytes'])}. "
                 f"The 1D rolling array needs only {_mib(e2_dp1['peak_bytes'])} at W = {w_max}. "
                 f"Greedy-by-ratio stays flat at about {_ms(e2_gr['seconds'])}; DP is {speedup_w:.0f}x slower there.")
    lines.append("Charts: `charts/exp2_runtime_vs_capacity.png`, `charts/exp2_memory_vs_capacity.png`.")
    lines.append("")

    lines.append("## Experiment 3: greedy quality on random instances (`exp3_quality.csv`, `exp3_quality_summary.csv`)")
    lines.append("")
    lines.append("| greedy variant | instance type | instances | mean % of optimum | min % | % of instances optimal |")
    lines.append("|---|---|---|---|---|---|")
    for r in e3:
        lines.append(f"| {common.LABELS[r['greedy']]} | {r['correlation']} | {r['instances']} | "
                     f"{r['mean_quality_percent']} | {r['min_quality_percent']} | {r['percent_optimal']} |")
    lines.append("")
    lines.append(f"Headline: greedy-by-ratio averaged {ratio_all['mean_quality_percent']}% of the DP optimum and was "
                 f"exactly optimal on {ratio_all['percent_optimal']}% of all {ratio_all['instances']} instances "
                 f"(worst case {ratio_all['min_quality_percent']}%). Greedy-by-value averaged "
                 f"{value_all['mean_quality_percent']}% and was optimal on {value_all['percent_optimal']}% "
                 f"(worst case {value_all['min_quality_percent']}%).")
    lines.append("Chart: `charts/exp3_quality_hist.png`.")
    lines.append("")

    lines.append("## Experiment 4: hand-built failure cases (`exp4_failure_cases.csv`)")
    lines.append("")
    lines.append("| case | capacity | optimal (DP) | greedy by ratio | gap % | greedy by value | gap % |")
    lines.append("|---|---|---|---|---|---|---|")
    cases = []
    for r in e4:
        if r["case"] not in cases:
            cases.append(r["case"])
    for c in cases:
        d = pick(e4, case=c, algorithm="dp_2d")
        g = pick(e4, case=c, algorithm="greedy_ratio")
        v = pick(e4, case=c, algorithm="greedy_value")
        lines.append(f"| {c} | {d['capacity']} | {d['value']} | {g['value']} | {float(g['gap_percent']):.1f} | "
                     f"{v['value']} | {float(v['gap_percent']):.1f} |")
    lines.append("")
    lines.append("Chart: `charts/exp4_failure_cases.png`.")
    lines.append("")

    with open(SUMMARY_PATH, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"[run_all] wrote {SUMMARY_PATH}")


def main() -> None:
    common.ensure_dirs()
    timings = {}
    for label, module in (("exp1_items", exp1_items), ("exp2_capacity", exp2_capacity),
                          ("exp3_quality", exp3_quality), ("exp4_failure_cases", exp4_failure_cases)):
        print(f"\n##### Running {label} #####")
        t0 = time.perf_counter()
        module.main()
        timings[label] = time.perf_counter() - t0
    write_summary(timings)
    print(f"[run_all] finished all experiments in {sum(timings.values()):.1f} s")


if __name__ == "__main__":
    main()
